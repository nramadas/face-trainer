/**
 * Build the default new-emotion order and write src/data/order.ts.
 *   npx tsx --tsconfig tsconfig.node.json scripts/make-order.ts
 *
 * Rules: the fixed starting 20 first; then face and face-body tiers before
 * context; never more than two from the same group in a row; look-alikes at
 * least 3 places apart.
 */
import { writeFileSync } from 'node:fs';
import { EMOTIONS, lookAlikeIds, getEmotion } from '../src/data/emotions/index';
import { START_ORDER, MIN_LOOKALIKE_GAP } from '../src/data/orderRules';

const tierRank = { face: 0, 'face-body': 1, context: 2 } as const;
const rest = EMOTIONS.filter((e) => !START_ORDER.includes(e.id));
// Round-robin over groups inside each tier, so groups mix.
const byTier = [0, 1, 2].map((t) => rest.filter((e) => tierRank[e.tier] === t));
const pool: string[] = [];
for (const list of byTier) {
  const groups = [...new Set(list.map((e) => e.group))];
  const queues = groups.map((g) => list.filter((e) => e.group === g).map((e) => e.id));
  while (queues.some((q) => q.length)) for (const q of queues) if (q.length) pool.push(q.shift()!);
}

const order = [...START_ORDER];
const ok = (id: string) => {
  const e = getEmotion(id)!;
  const n = order.length;
  if (n >= 2 && getEmotion(order[n - 1])!.group === e.group && getEmotion(order[n - 2])!.group === e.group) return false;
  const look = new Set(lookAlikeIds(id));
  for (let k = 1; k < MIN_LOOKALIKE_GAP; k++) if (n - k >= 0 && look.has(order[n - k])) return false;
  return true;
};
while (pool.length) {
  const i = pool.findIndex(ok);
  if (i < 0) throw new Error(`No valid next emotion after ${order.at(-1)}; remaining: ${pool.join(', ')}`);
  order.push(pool.splice(i, 1)[0]);
}

const lines = [];
for (let i = 0; i < order.length; i += 8) lines.push('  ' + order.slice(i, i + 8).map((x) => `'${x}'`).join(', ') + ',');
writeFileSync(
  'src/data/order.ts',
  `/**
 * Default order of new emotions. Generated by scripts/make-order.ts; checked by
 * src/data/emotions.test.ts. The user can change it with "Learn this next".
 */
export const DEFAULT_ORDER: readonly string[] = [
${lines.join('\n')}
];
`,
);
